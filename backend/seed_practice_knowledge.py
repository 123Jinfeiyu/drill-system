async def seed_knowledge():
    """将业务知识导入知识库"""
    await init_db()
    async with AsyncSessionLocal() as db:
        result = await db.execute(select(KnowledgeItem))
        existing = {item.title for item in result.scalars().all()}
        created = 0
        for item_data in KNOWLEDGE_DATA:
            if item_data["title"] in existing:
                continue
            kb = KnowledgeItem(
                title=item_data["title"],
                content=item_data["content"],
                tags=item_data["tags"],
                source_url="桔多多融合业务.docx / 客服话术总库.xlsx",
            )
            db.add(kb)
            created += 1
        await db.commit()
        print(f"知识库种子完成：新增 {created} 条，跳过 {len(KNOWLEDGE_DATA) - created} 条已存在")
    await engine.dispose()


if __name__ == "__main__":
    asyncio.run(seed_knowledge())
