async def main():
    await init_db()
    async with AsyncSessionLocal() as db:
        created = 0
        skipped = 0
        for s_data in SCENARIOS:
            existing = await db.execute(
                select(Scenario).where(Scenario.code == s_data["code"])
            )
            if existing.scalar_one_or_none():
                print(f"  跳过（已存在）: {s_data['code']} - {s_data['title']}")
                skipped += 1
                continue
            s = Scenario(**s_data)
            db.add(s)
            created += 1
            print(f"  导入: {s_data['code']} - {s_data['title']}")
        await db.commit()
        print(f"\n完成：导入 {created} 个场景，跳过 {skipped} 个已存在场景")


if __name__ == "__main__":
    asyncio.run(main())
